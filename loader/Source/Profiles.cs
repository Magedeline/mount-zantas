using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Monocle;

namespace Celeste.Mod.ZantasLoader;

// A profile is a named copy of the set of disabled mods (the entries of Mods/blacklist.txt).
// Applying one rewrites blacklist.txt, which takes effect on the next game start.
public static class Profiles {
    // Kept automatically: whatever blacklist.txt held before the last Apply.
    public const string PreviousName = "previous";

    // In the saves folder, not in Mods: Everest would load a folder inside Mods as a mod.
    public static string Dir => Path.Combine(Everest.PathSettings, "zantas-profiles");

    private static string PathOf(string name) => Path.Combine(Dir, name + ".txt");

    // Letters, digits, spaces, '-' and '_' only, so a name is always a safe file name.
    public static string CleanName(string name) {
        if (name == null)
            return "";
        StringBuilder sb = new StringBuilder();
        foreach (char c in name.Trim())
            if (char.IsLetterOrDigit(c) || c == ' ' || c == '-' || c == '_')
                sb.Append(c);
        string clean = sb.ToString().Trim();
        return clean.Length > 32 ? clean.Substring(0, 32).Trim() : clean;
    }

    public static List<string> List() {
        if (!Directory.Exists(Dir))
            return new List<string>();
        return Directory.GetFiles(Dir, "*.txt")
            .Select(Path.GetFileNameWithoutExtension)
            .OrderBy(n => n == PreviousName ? 1 : 0)
            .ThenBy(n => n, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private static List<string> ReadEntries(string path) {
        if (!File.Exists(path))
            return new List<string>();
        return File.ReadAllLines(path)
            .Select(l => l.Trim())
            .Where(l => l.Length > 0 && !l.StartsWith("#"))
            .Distinct()
            .ToList();
    }

    // The mods currently disabled on disk (which is what the next game start will use).
    public static List<string> CurrentDisabled() => ReadEntries(Everest.Loader.PathBlacklist);

    public static List<string> Read(string name) => ReadEntries(PathOf(CleanName(name)));

    public static bool Exists(string name) => File.Exists(PathOf(CleanName(name)));

    private static void Write(string name, List<string> disabled) {
        Directory.CreateDirectory(Dir);
        List<string> lines = new List<string> {
            $"# Zantas mod profile \"{name}\": the mods listed here are disabled when it is applied."
        };
        lines.AddRange(disabled);
        File.WriteAllLines(PathOf(name), lines);
    }

    // Returns the cleaned name the profile was saved under, or null if the name was unusable.
    public static string Save(string name) {
        name = CleanName(name);
        if (name.Length == 0 || name == PreviousName)
            return null;
        Write(name, CurrentDisabled());
        return name;
    }

    public static bool Delete(string name) {
        name = CleanName(name);
        if (!Exists(name))
            return false;
        File.Delete(PathOf(name));
        return true;
    }

    // Rewrites blacklist.txt from the profile. The old contents are kept as the "previous" profile.
    public static bool Apply(string name) {
        name = CleanName(name);
        if (!Exists(name))
            return false;

        List<string> disabled = Read(name);
        if (name != PreviousName)
            Write(PreviousName, CurrentDisabled());

        List<string> lines = new List<string> {
            "# This is the blacklist. Lines starting with # are ignored.",
            $"# File generated by Zantas Loader from the mod profile \"{name}\"",
            ""
        };
        lines.AddRange(disabled);
        File.WriteAllLines(Everest.Loader.PathBlacklist, lines);
        return true;
    }

    [Command("zantas_profile_list", "Zantas Loader: list saved mod profiles")]
    public static void CmdList() {
        List<string> names = List();
        if (names.Count == 0) {
            Engine.Commands.Log("No profiles saved yet. use zantas_profile_save <name>.");
            return;
        }
        foreach (string name in names)
            Engine.Commands.Log($"{name}: {Read(name).Count} mods disabled");
        Engine.Commands.Log($"Right now {CurrentDisabled().Count} mods are disabled in blacklist.txt.");
    }

    [Command("zantas_profile_save", "Zantas Loader: save the currently disabled mods as a profile. Argument: name")]
    public static void CmdSave(string name) {
        string saved = Save(name);
        Engine.Commands.Log(saved == null
            ? "Give a name using letters, digits, spaces, - or _ (\"previous\" is reserved)."
            : $"Saved profile \"{saved}\" with {Read(saved).Count} mods disabled.");
    }

    [Command("zantas_profile_apply", "Zantas Loader: write a profile to blacklist.txt (takes effect after restarting the game). Argument: name")]
    public static void CmdApply(string name) {
        Engine.Commands.Log(Apply(name)
            ? $"Applied \"{CleanName(name)}\". Restart the game for it to take effect. The old set is saved as \"{PreviousName}\"."
            : $"No profile named \"{CleanName(name)}\".");
    }

    [Command("zantas_profile_delete", "Zantas Loader: delete a saved profile. Argument: name")]
    public static void CmdDelete(string name) {
        Engine.Commands.Log(Delete(name)
            ? $"Deleted profile \"{CleanName(name)}\"."
            : $"No profile named \"{CleanName(name)}\".");
    }
}
